import json
import logging
import os
import uuid
from decimal import Decimal

import boto3

# Configure CloudWatch logging
logger = logging.getLogger()
logger.setLevel(logging.INFO)

# Table name comes from the Lambda environment variable
dynamodb = boto3.resource("dynamodb")
table = dynamodb.Table(os.environ["DYNAMODB_TABLE"])


# Convert DynamoDB numbers (Decimal) back to normal JSON numbers
class DecimalEncoder(json.JSONEncoder):
    def default(self, o):
        if isinstance(o, Decimal):
            return int(o) if o == o.to_integral_value() else float(o)
        return super().default(o)


def response(status, body=None):
    return {
        "statusCode": status,
        "headers": {"Content-Type": "application/json"},
        "body": "" if body is None else json.dumps(body, cls=DecimalEncoder),
    }


# Validate the request body (must be a non-empty JSON object)
def parse_body(event):
    try:
        body = json.loads(event.get("body") or "", parse_float=Decimal)
    except ValueError:
        return None, response(400, {"error": "Request body must be valid JSON"})
    if not isinstance(body, dict) or not body:
        return None, response(400, {"error": "Request body must be a non-empty JSON object"})
    return body, None


# CREATE
def create_item(event):
    body, error = parse_body(event)
    if error:
        return error
    body.pop("id", None)  # id is always generated by the server
    item = {**body, "id": str(uuid.uuid4())}
    table.put_item(Item=item)
    return response(201, {"message": "Item created", "item": item})


# READ (all items)
def list_items():
    items = table.scan().get("Items", [])
    return response(200, items)


# READ (one item)
def get_item(item_id):
    item = table.get_item(Key={"id": item_id}).get("Item")
    if not item:
        return response(404, {"error": "Item not found"})
    return response(200, item)


# UPDATE
def update_item(event, item_id):
    body, error = parse_body(event)
    if error:
        return error
    body.pop("id", None)  # id can't be changed
    if not body:
        return response(400, {"error": "No fields to update"})

    # Placeholders (#f0, :v0) so reserved words like "name" or "status" work
    sets, names, values = [], {}, {}
    for i, (field, value) in enumerate(body.items()):
        sets.append(f"#f{i} = :v{i}")
        names[f"#f{i}"] = field
        values[f":v{i}"] = value

    table.update_item(
        Key={"id": item_id},
        UpdateExpression="SET " + ", ".join(sets),
        ExpressionAttributeNames=names,
        ExpressionAttributeValues=values,
    )
    return response(200, {"message": "Item updated", "id": item_id})


# DELETE
def delete_item(item_id):
    table.delete_item(Key={"id": item_id})
    return response(200, {"message": "Item deleted", "id": item_id})


def lambda_handler(event, context):
    logger.info("Event received: %s", json.dumps(event))

    # routeKey matches the routes in 08-API-Gateway.tf, e.g. "GET /items/{id}"
    route = event.get("routeKey", "")
    item_id = (event.get("pathParameters") or {}).get("id")

    try:
        if route == "GET /":
            return response(200, {"message": "TFP2 serverless API is running"})
        if route in ("HEAD /", "OPTIONS /"):
            return response(200)
        if route == "POST /items":
            return create_item(event)
        if route == "GET /items":
            return list_items()
        if route == "GET /items/{id}":
            return get_item(item_id)
        if route == "PUT /items/{id}":
            return update_item(event, item_id)
        if route == "DELETE /items/{id}":
            return delete_item(item_id)

        return response(404, {"error": "Route not found"})
    except Exception:
        # Logged as ERROR so the CloudWatch error alarm picks it up
        logger.exception("Error processing %s", route)
        return response(500, {"error": "Internal server error"})
